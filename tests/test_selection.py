import os,sys;sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from helpers import APP,OUT,FAKE,on_dialog
import json
from playwright.sync_api import sync_playwright
errs=[]
def ok(c,m):
    print(("OK   " if c else "FAIL ")+m)
    if not c: errs.append(m)
T=[{"id":"t%d"%i,"projectId":"p","title":"Tâche %d"%i,"priority":"normale","due":"","status":"todo","createdAt":i} for i in range(1,7)]
P=[{"id":"o%d"%i,"projectId":"p","text":"Point %d"%i,"answer":"","hypothesis":"","erp":"","theme":"Réception","owner":"","ownerName":"","status":"open","createdAt":i} for i in range(1,5)]
data={"projects":[{"id":"p","name":"Projet Alpha","color":"#E0703A","pointThemes":[{"id":"th1","name":"Réception"},{"id":"th2","name":"Expédition"}]},{"id":"q","name":"Projet Bêta","color":"#2F7D5B"}],"tasks":T,"requests":[],"points":P,"deleted":[]}
with sync_playwright() as pw:
    b=pw.chromium.launch();pg=b.new_page(viewport={"width":1440,"height":1000})
    pg.on("pageerror",lambda e:errs.append("JS: "+str(e)))
    on_dialog(pg,lambda d:d.accept("Client" if d.type=="prompt" else None))
    pg.add_init_script("if(!localStorage.getItem('__seed')){localStorage.setItem('todo-projets',%s);localStorage.setItem('todo-mode','local');localStorage.setItem('todo-projets-ui','{}');localStorage.setItem('__seed','1')}"%json.dumps(json.dumps(data)))
    pg.goto(APP);pg.wait_for_timeout(300)
    st=lambda:pg.evaluate("JSON.parse(localStorage.getItem('todo-projets'))")
    tk=lambda i:[x for x in st()["tasks"] if x["id"]==i][0]
    po=lambda i:[x for x in st()["points"] if x["id"]==i][0]
    pg.locator(".pbtn",has_text="Projet Alpha").click()
    pg.locator("#viewbar button",has_text="Sélectionner").click()
    ok(pg.locator("#selbar").is_visible(),"mode sélection : barre d'actions affichée")
    pg.locator('.task[data-id="t1"]').click();pg.locator('.task[data-id="t3"]').click(modifiers=["Shift"])
    ok("3 sélectionnées" in pg.locator("#selbar").inner_text(),"clic puis Maj+clic : plage de 3 tâches")
    ok(tk("t1")["status"]=="todo","clic en mode sélection : la tâche n'est pas cochée")
    pg.screenshot(path=OUT+"selection_tasks.png")
    pg.select_option('#selbar select[data-sk="st"]',"done");pg.wait_for_timeout(200)
    ok(all(tk(i)["status"]=="done" for i in ["t1","t2","t3"]) and tk("t4")["status"]=="todo","statut groupé : 3 terminées")
    pg.select_option('#selbar select[data-sk="prio"]',"haute");pg.wait_for_timeout(200)
    ok(all(tk(i)["priority"]=="haute" for i in ["t1","t2","t3"]),"priorité groupée")
    pg.select_option('#selbar select[data-sk="due"]',"tom");pg.wait_for_timeout(200)
    ok(all(tk(i)["due"] for i in ["t1","t2","t3"]),"échéance groupée (demain)")
    pg.select_option('#selbar select[data-sk="who"]',"__other");pg.wait_for_timeout(300)
    ok(all(tk(i)["who"]=="Client" for i in ["t1","t2","t3"]),"responsable groupé (autre personne)")
    pg.locator("#toast button").click();pg.wait_for_timeout(200)
    ok(not tk("t1").get("who"),"annulation de la dernière action groupée")
    pg.locator("#selbar [data-sa=all]").click()
    ok("6 sélectionnées" in pg.locator("#selbar").inner_text(),"tout sélectionner")
    pg.select_option('#selbar select[data-sk="proj"]',"q");pg.wait_for_timeout(200)
    ok(all(t["projectId"]=="q" for t in st()["tasks"]),"déplacer vers un autre projet")
    pg.locator("#toast button").click();pg.wait_for_timeout(200)
    pg.locator("#selbar [data-sa=none]").click()
    pg.locator('.task[data-id="t4"]').click();pg.locator('.task[data-id="t5"]').click()
    pg.locator("#selbar [data-sa=trash]").click();pg.wait_for_timeout(200)
    ok(tk("t4").get("deletedAt") and tk("t5").get("deletedAt"),"corbeille groupée")
    pg.keyboard.press("Escape");pg.wait_for_timeout(100)
    ok(pg.locator("#selbar").count()==0 and pg.locator(".selbox").count()==0,"Échap : sortie du mode sélection")
    # points ouverts
    pg.locator('#ptabs [data-tab="points"]').click()
    pg.locator("#viewbar button",has_text="Sélectionner").click()
    pg.locator('.pt[data-o="o1"]').click();pg.locator('.pt[data-o="o2"]').click()
    ok("2 sélectionnés" in pg.locator("#selbar").inner_text(),"points : 2 sélectionnés")
    pg.select_option('#selbar select[data-sk="th"]',"Expédition");pg.wait_for_timeout(200)
    pg.select_option('#selbar select[data-sk="ow"]',"client");pg.wait_for_timeout(200)
    pg.select_option('#selbar select[data-sk="erp"]',"oui");pg.wait_for_timeout(200)
    ok(po("o1")["theme"]=="Expédition" and po("o2")["owner"]=="client" and po("o1")["erp"]=="oui" and po("o3")["theme"]=="Réception","points : thème, interlocuteur, ERP groupés")
    pg.select_option('#selbar select[data-sk="pst"]',"closed");pg.wait_for_timeout(200)
    ok(po("o1")["status"]=="closed" and po("o2")["closedAt"],"points : levés en groupe")
    pg.locator("#toast button").click();pg.wait_for_timeout(200)
    ok(po("o1")["status"]=="open","points : annulation")
    pg.screenshot(path=OUT+"selection_points.png")
    pg.locator('.pbtn',has_text="Projet Bêta").click()
    ok(pg.locator("#selbar").count()==0,"changement de projet : sélection quittée")
    m=pg;m.set_viewport_size({"width":390,"height":800})
    m.reload();m.wait_for_timeout(300);m.evaluate("document.querySelector('.pbtn').click()");m.wait_for_timeout(100);m.locator(".phtile",has_text="Tâches").click();m.wait_for_timeout(100)
    m.locator("#viewbar .vbfilt").click();m.locator("#viewbar button",has_text="Sélectionner").click();m.locator(".task").first.click()
    ok(m.evaluate("document.documentElement.scrollWidth<=390"),"mobile : pas de débordement horizontal")
    m.screenshot(path=OUT+"selection_mobile.png")
    b.close()
print("ERREURS :",errs or "aucune")
sys.exit(1 if errs else 0)
